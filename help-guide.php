<h2 id="start">۱. ورود به سامانه و آشنایی با منو</h2>
<h3>ورود</h3>
<div class="step"><b class="n">۱</b>مرورگر را باز کنید و نشانی سامانه را وارد کنید.</div>
<div class="step"><b class="n">۲</b>نام کاربری و کلمه عبور سازمانی (همان مشخصات ورود به کامپیوتر) را وارد کنید.</div>
<div class="step"><b class="n">۳</b>روی «ورود» کلیک کنید. پس از ورود، صفحهٔ داشبورد باز می‌شود.</div>
<div class="warn">اگر ورود انجام نشد، ابتدا بررسی کنید حروف کلمه عبور درست باشد و کلید Caps Lock روشن نباشد. اگر باز هم مشکل داشتید، با واحد پشتیبانی تماس بگیرید.</div>

