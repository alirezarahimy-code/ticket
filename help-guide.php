<h2 id="faq">۱۲. پرسش‌های متداول</h2>
<h3>چرا فیلد «سیستم مرتبط» را نمی‌بینم؟</h3>
<p>این فیلد فقط وقتی نمایش داده می‌شود که نوع تیکت «پشتیبانی» و حوزهٔ خدمت «خدمات کامپیوتری و IT» باشد.</p>
<h3>چرا برای یک روز نمی‌توانم سفارش بدهم؟</h3>
<p>روزهای گذشته فقط قابل مشاهده هستند. همچنین اگر روز در برنامهٔ غذایی «بسته» باشد، سفارش پذیرفته نمی‌شود.</p>
<h3>چرا سفارش‌های من در فهرست نیست؟</h3>
<p>فهرست به‌طور پیش‌فرض ماه شمسی جاری را نشان می‌دهد. برای دیدن ماه‌های دیگر از فیلتر بازهٔ تاریخ استفاده کنید.</p>
<h3>ثبت کارمند یا گروه با خطا متوقف شد؛ چه کنم؟</h3>
<p>پیام خطای فارسی را بخوانید. اگر کد ملی یا L-UID تکراری است، مقدار دیگری وارد کنید. اگر پیام نامفهوم بود، صفحه را عکس بگیرید و به پشتیبانی بدهید.</p>
<h3>با کدام واحد تماس بگیرم؟</h3>
<p>برای مشکلات فنی، یک تیکت در بخش «تیکت» ثبت کنید. برای مسائل مربوط به سفارش غذا، با مسئول غذا تماس بگیرید.</p>

