  <h3>افزودن یک کارمند</h3>
  <div class="step"><b class="n">۱</b>بخش «کارکنان» را باز کنید و «افزودن» را بزنید.</div>
  <div class="step"><b class="n">۲</b>کد پرسنلی، کد ملی، نام و نام خانوادگی را وارد کنید.</div>
  <div class="step"><b class="n">۳</b>ذخیره کنید. کد پرسنلی باید یکتا باشد.</div>
  <div class="example"><b>مثال:</b> کارمند جدید با کد پرسنلی ۱۰۴۵ و کد ملی ۰۰۱۲۳۴۵۶۷۹ را ثبت می‌کنید. اگر کد ۱۰۴۵ قبلاً ثبت شده باشد، سامانه اجازه نمی‌دهد.</div>
  <div class="warn"><b>سفارش برای کارمند دیگر:</b> هر کاربری که وارد سامانه شده باشد می‌تواند با کد ملی همکارش برای او غذا سفارش دهد. نیازی به داشتن حساب برای همکار نیست.</div>

  <h2 id="food-menu">۷. برنامه غذایی و گروه‌ها</h2>
  <p>برنامه غذایی یعنی اینکه هر روز چه غذایی سرو می‌شود. از تقویم روز را انتخاب کنید و در ویرایشگر روز، غذاها را تیک بزنید.</p>
  <figure>
    <img src="assets/help/panel-food-menu.png" alt="برنامه غذایی" loading="lazy">
    <figcaption>برنامه غذایی: تقویم در سمت چپ و ویرایشگر روز در سمت راست.</figcaption>
