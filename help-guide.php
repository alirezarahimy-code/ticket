  <h2 id="dashboard">۲. داشبورد و منوها</h2>
  <p>بعد از ورود، منوی بالا شما را به بخش‌های مجاز می‌برد. بخش‌هایی که به آن‌ها دسترسی ندارید، نمایش داده نمی‌شوند. این دسترسی‌ها توسط مدیر تعیین می‌شود (بخش ۴).</p>
  <table>
    <tr><th>منو</th><th>کاربرد</th></tr>
    <tr><td>داشبورد</td><td>خلاصهٔ وضعیت امروز و هفته</td></tr>
    <tr><td>پایش لحظه‌ای</td><td>ترددهای زنده و فیش‌های در حال چاپ</td></tr>
    <tr><td>کارکنان</td><td>فهرست پرسنل، کد پرسنلی و کد ملی</td></tr>
    <tr><td>برنامه غذایی</td><td>تعیین غذای هر روز با تقویم</td></tr>
    <tr><td>گروه‌های غذا</td><td>گروه‌بندی کارکنان برای غذا</td></tr>
    <tr><td>گزارش‌ها</td><td>خروجی CSV و چاپ گزارش</td></tr>
    <tr><td>تنظیمات سیستم</td><td>اتصال‌ها، چاپگر، کارت مهمان، طراحی فیش، سلامت سیستم</td></tr>
  </table>
  <div class="example"><b>مثال:</b> کارشناس آشنا با داشبورد، صبح وارد می‌شود و عدد «کارکنان فعال» و نمودار هفت روز اخیر را نگاه می‌کند تا ببیند امروز چند فیش صادر شده است.</div>

  <h2 id="tickets">۳. تیکت‌ها و خدمات</h2>
  <p>کاربران برای درخواست پشتیبانی تیکت ثبت می‌کنند و وضعیت آن را پیگیری می‌کنند. کارشناسان تیکت‌ها را از «صف کاری» برمی‌دارند و پاسخ می‌دهند. بعد از حل شدن، کاربر می‌تواند تیکت را امتیاز دهد.</p>
  <h3>مراحل ثبت تیکت</h3>
  <div class="step"><b class="n">۱</b>از منوی «خدمات» گزینهٔ مناسب را انتخاب کنید.</div>
  <div class="step"><b class="n">۲</b>دسته، شرح مشکل و در صورت نیاز فایل پیوست را وارد کنید.</div>
  <div class="step"><b class="n">۳</b>ثبت را بزنید. شماره تیکت نشان داده می‌شود؛ با آن می‌توانید پیگیری کنید.</div>
  <div class="example"><b>مثال:</b> کاربر «سارا رضایی» رایانه‌اش به چاپگر وصل نمی‌شود. او از «خدمات»، دستهٔ «چاپگر» را انتخاب می‌کند، می‌نویسد «خطای اتصال به چاپگر طبقهٔ دوم»، و شماره تیکت ۱۲۳۴ را دریافت می‌کند.</div>
  <div class="todo">تصویر فرم ثبت تیکت و صف کاری در این نسخه گرفته نشده است. (جای تصویر: <code>assets/help/tickets-new.png</code>)</div>

  <h2 id="roles">۴. نقش‌ها و دسترسی‌ها</h2>
  <p>هر کاربر یک <b>نقش</b> دارد و نقش، دسترسی‌ها را مشخص می‌کند. مدیر سامانه در «تنظیمات سیستم > نقش‌ها و دسترسی‌ها» می‌تواند برای هر نقش و هر بخش، سطح دسترسی (مشاهده یا ویرایش) را تنظیم کند.</p>
  <table>
    <tr><th>عنوان در سامانه</th><th>نقش فنی</th><th>توضیح</th></tr>
    <tr><td>کارشناس آی‌تی</td><td>primary_admin</td><td>ادمین اصلی؛ دسترسی کامل</td></tr>
    <tr><td>کارشناس پشتیبانی</td><td>support_manager</td><td>مدیر پشتیبانی؛ بدون دسترسی به تنظیمات</td></tr>
    <tr><td>کارشناس</td><td>agent</td><td>پاسخ‌دهندهٔ تیکت</td></tr>
    <tr><td>کاربر</td><td>user</td><td>ثبت تیکت و مشاهدهٔ وضعیت خود</td></tr>
    <tr><td>مدیر</td><td>manager</td><td>تعیین خودکار از روی چارت سازمانی (معاونت یا مدیر اداره)</td></tr>
  </table>
  <div class="warn"><b>نکته:</b> نقش‌های بازرس، سرپرست و مدیر پشتیبانی برای هر کاربر به‌صورت دستی تعیین می‌شوند و همگام‌سازی سازمانی آن‌ها را تغییر نمی‌دهد. اگر کاربری از سمت معاونت یا مدیر اداره حذف شود، نقش قبلی‌اش برمی‌گردد.</div>
  <div class="example"><b>مثال:</b> «رضا احمدی» در چارت سازمانی به‌عنوان «مدیر اداره» ثبت شده است. سامانه نقش او را خودکار به «مدیر» تغییر می‌دهد. وقتی این سمت از او برداشته شود، نقش قبلی‌اش (مثلاً کاربر) برمی‌گردد.</div>

  <h2 id="traffic">۵. کنترل تردد</h2>
  <p>این بخش ورود و خروج مراجعین را ثبت می‌کند. از آن می‌فهمید <b>چه کسی الان داخل ساختمان است</b>. سقف فیش مهمان هم در حالت متغیر از همین ثبت‌ها محاسبه می‌شود (بخش ۸).</p>
  <h3>زبانه‌ها</h3>
  <table>
    <tr><th>زبانه</th><th>کاربرد</th></tr>
    <tr><td>داشبورد</td><td>آمار و نمودارهای ترددها، و <b>فهرست ترددهای بدون خروج</b> که زیر نمودارها آمده است</td></tr>
    <tr><td>ثبت تردد</td><td>فرم ورود مراجع جدید</td></tr>
    <tr><td>سوابق</td><td>جستجو، فیلتر «فقط بدون خروج»، چاپ برگ، ثبت خروج</td></tr>
    <tr><td>مقصدهای ملاقات</td><td>تعریف مقصدها (فقط مدیر)</td></tr>
  </table>
  <h3>ثبت ورود یک مراجع</h3>
  <div class="step"><b class="n">۱</b>زبانهٔ «ثبت تردد» را باز کنید.</div>
  <div class="step"><b class="n">۲</b>کد ملی را صحیح وارد کنید. اگر سابقه داشته باشد، اطلاعات آن پر می‌شود.</div>
  <div class="step"><b class="n">۳</b>نام، ملاقات با (از فهرست مقصدها)، و تأییدکننده را وارد کنید.</div>
  <div class="step"><b class="n">۴</b>«ثبت تردد» را بزنید. شماره برگ ساخته می‌شود و می‌توانید برگ را چاپ کنید.</div>
  <div class="warn"><b>خطای کد ملی:</b> اگر کد ملی نامعتبر باشد، پیام خطا بالای فرم می‌آید و کادر کد ملی فوکوس می‌گیرد. مقدارهای دیگر فرم حفظ می‌شوند.</div>
  <h3>ثبت خروج</h3>
  <p>در داشبورد، زیر نمودارها، فهرست «ترددهای بدون خروج» است. برای ثبت خروج، دکمهٔ «ثبت خروج» را بزنید.</p>
  <div class="example"><b>مثال:</b> مراجع «حسین کریمی» ساعت ۱۰:۱۵ آمده و ساعت ۱۱:۴۰ می‌رود. کارشناس در داشبورد دکمهٔ «ثبت خروج» کنار نام او را می‌زند و ساعت ۱۱:۴۰ ثبت می‌شود. اگر او را فراموش کنید، هنوز در فهرست است.</div>
  <div class="example"><b>مثال روزهای قبل:</b> تردد دیروز که هنوز خروج ندارد در همین فهرست می‌ماند. تا وقتی خروج آن ثبت نشود، در فهرست دیده می‌شود؛ سامانه آن را خودکار نمی‌بندد.</div>
  <div class="todo">تصویر فرم ثبت تردد و فهرست بدون خروج در این نسخه گرفته نشده است. (جای تصویر: <code>assets/help/traffic-dashboard.png</code>)</div>

  <h2 id="food">۶. چاپ فیش غذا: داشبورد و کارکنان</h2>
  <p>کارکنان با کارت RFID یا ثبت سفارش، فیش غذا می‌گیرند. فیش‌ها به چاپگر ارسال می‌شوند و در پایش لحظه‌ای دیده می‌شوند.</p>
