  <h2 id="start">۱. شروع کار و ورود</h2>
  <p>سامانه دو نوع کاربر دارد:</p>
  <ul>
    <li><b>کاربران دامنه (AD):</b> با همان نام کاربری و رمز ویندوز یا دامنهٔ سازمان وارد می‌شوند.</li>
    <li><b>کارکنان غیر دامنه:</b> حساب ورود ندارند. فقط می‌توانند با کد ملی برای خودشان یا همکارانشان غذا سفارش دهند.</li>
  </ul>
  <h3>مراحل ورود</h3>
  <div class="step"><b class="n">۱</b>آدرس سامانه را در مرورگر باز کنید.</div>
  <div class="step"><b class="n">۲</b>نام کاربری و رمز عبور را وارد کنید.</div>
  <div class="step"><b class="n">۳</b>روی «ورود» بزنید. بعد از ورود، صفحهٔ داشبورد باز می‌شود.</div>
  <div class="example"><b>مثال:</b> کارشناس «علی محمدی» با حساب دامنه‌اش (همان نام کاربری و رمز ویندوز) وارد می‌شود.</div>
