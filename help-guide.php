  <h2 id="faq">۱۲. سؤالات رایج و خطاها</h2>
  <h3>چرا دکمه‌ای یا بخشی را نمی‌بینم؟</h3>
  <p>دسترسی شما در نقش‌ها تعیین شده است. از مدیر سامانه بخواهید نقش یا سطح دسترسی شما را بررسی کند.</p>
  <h3>پیام «کد ملی معتبر نیست» می‌گیرم</h3>
  <p>کد ملی را بدون اشتباه و کامل وارد کنید. اگر سامانه نپذیرفت، ارقام را یک‌بار دیگر با کارت ملی مقایسه کنید.</p>
  <h3>فیش مهمان صادر نمی‌شود</h3>
  <p>سقف فعلی را در بخش کارت مهمان ببینید. اگر سقف صفر است یا ساعت خارج از بازهٔ ۱۱ تا ۱۵ است، فیش صادر نمی‌شود. در حالت سقف ثابت، عدد سقف را بررسی کنید.</p>
  <h3>ترددی را اشتباه ثبت کرده‌ام</h3>
  <p>اگر ردیف اشتباه است، از مدیر سامانه بخواهید آن را بررسی یا اصلاح کند.</p>
  <h3>چاپ نمی‌شود</h3>
  <ol>
    <li>در «سلامت سیستم» وضعیت سرویس‌ها و چاپگر را ببینید.</li>
    <li>در «چاپگر سیستم» روش چاپ و مشخصات را بررسی کنید.</li>
    <li>اگر مشکل ادامه داشت، پیام خطا را برای پشتیبانی بفرستید.</li>
  </ol>
  <div class="example"><b>یادآوری:</b> برای خطای ناشناخته، تیکت جدید ثبت کنید و در شرح، زمان دقیق و پیام خطا را بنویسید. این کار سرعت رسیدگی را خیلی بالا می‌برد.</div>
