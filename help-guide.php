  <h3>تعیین غذای یک روز</h3>
  <div class="step"><b class="n">۱</b>روز مورد نظر را در تقویم انتخاب کنید.</div>
  <div class="step"><b class="n">۲</b>در ویرایشگر روز، غذاهای آن روز را تیک بزنید. فهرست دو ستونه است و نام‌های بلند کامل نمایش داده می‌شوند.</div>
  <div class="step"><b class="n">۳</b>ذخیره کنید.</div>
  <div class="example"><b>مثال:</b> برای شنبه، «چلوکباب» و «ماست» را تیک می‌زنید. کارکنان در همان روز فقط همین دو گزینه را می‌بینند.</div>
  <h3>گروه‌های غذا</h3>
  <p>گروه‌ها کارکنان را دسته‌بندی می‌کنند، مثلاً «نگهبانان» یا «طبقهٔ دوم». هر گروه می‌تواند غذای مخصوص خودش یا تنظیمات ویژه داشته باشد.</p>
