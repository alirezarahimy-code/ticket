  <h3>تنظیم ساعت‌ها</h3>
  <p>سه ساعت (شروع، قطع، صفر شدن) را به صورت ۲۴ ساعته و به شکل <b>HH:MM</b> وارد کنید؛ مثلاً ۱۱:۰۰ یا ۱۵:۳۰. ساعت نامعتبر مثل ۲۴:۰۰ پذیرفته نمی‌شود.</p>
  <div class="warn"><b>توجه:</b> ساعت قطع پیش‌فرض ۱۲:۰۱ است. خروج‌هایی که در یا بعد از ۱۲:۰۱ ثبت شوند، سقف را کم نمی‌کنند.</div>

  <h2 id="printer">۹. چاپگر فیش</h2>
  <p>فیش‌ها به دو روش چاپ می‌شوند:</p>
  <ul>
    <li><b>چاپگر شبکه (TCP/RAW):</b> با آدرس IP و پورت (معمولاً 9100).</li>
    <li><b>صف چاپگر ویندوز:</b> چاپگری که روی سرور نصب شده، با نام آن در لیست.</li>
  </ul>
  <figure>
    <img src="assets/help/settings-printer.png" alt="تنظیمات چاپگر" loading="lazy">
    <figcaption>تنظیمات چاپگر: انتخاب روش چاپ و مشخصات چاپگر.</figcaption>
  </figure>
  <div class="step"><b class="n">۱</b>روش چاپ را انتخاب کنید.</div>
  <div class="step"><b class="n">۲</b>اگر شبکه است، IP و پورت؛ اگر ویندوز است، نام چاپگر را از لیست بزنید.</div>
  <div class="step"><b class="n">۳</b>ذخیره کنید؛ سپس صفحه را باز کنید و بررسی کنید که همان روش و همان مشخصات نمایش داده شوند.</div>
  <div class="example"><b>مثال:</b> چاپگر طبقهٔ همکف آدرس IP شبکه دارد. «چاپگر شبکه» را انتخاب می‌کنید، آدرس IP و پورت را وارد می‌کنید، ذخیره می‌کنید. بعد از ذخیره، همین حالت و همین IP باید نمایش داده شوند.</div>

