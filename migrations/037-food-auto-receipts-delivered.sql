-- تطبیق وضعیت «تحویل» ثبت‌های خودکار قدیمی با سیاست جدید وعده‌های سلف‌بسته؛ افزایشی و امن برای اجرای مجدد.
-- طبق تصمیم مالک (۱۴۰۵/۰۸)، وعده‌هایی که سلف تعطیل است (شام؛ ناهار در پنجشنبه/جمعه و تعطیلات رسمی)
-- به‌صورت سیستمی و بدون چاپ فیزیکی در سامانهٔ تحویل غذا ثبت می‌شوند؛ بنابراین ثبت‌های خودکارِ
-- پرسنل («auto_printed») که قبلاً «تحویل در انتظار» مانده بودند، به «تحویل‌شده» تبدیل می‌شوند.
-- مهمان‌ها («auto_guest») تحویل جداگانه‌ای ندارند و تغییر نمی‌کنند؛ هیچ ردیف فیزیکی چاپ‌شده‌ای دست نمی‌خورد.
UPDATE food_ticket_events
   SET delivery_status = 'delivered',
       delivered_at = COALESCE(delivered_at, processed_at)
 WHERE event_type = 'auto_printed'
   AND print_status = 'printed'
   AND delivery_status <> 'delivered';
