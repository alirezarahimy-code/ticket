'use strict';
// Exercise actual connector drawing with independently translated card rectangles.
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const src = fs.readFileSync('assets/organization.js', 'utf8');
const code = src.slice(src.indexOf('    var drawOrgWires = function () {'), src.indexOf('    var bindDeputyReorder = function () {'));
let paths = [];
const box = (left, top, width = 100, height = 50) => ({left, top, right:left+width, bottom:top+height, width, height});
const node = (rect, parent = null) => ({getBoundingClientRect: () => rect, closest: () => parent});
const root = node(box(200, 20));
const branch1 = {}, branch2 = {};
const a = node(box(30, 250), branch1), b = node(box(230, 380), branch2), office = node(box(40, 25));
const expert = node(box(100, 360)), child = node(box(200, 500));
const childRow = {querySelectorAll: () => [child]};
branch1.querySelector = q => ({':scope > .org-branch-card > .org-node': a, ':scope > .org-branch-card > .org-experts-group': expert, ':scope > .org-children': childRow})[q] || null;
branch2.querySelector = q => q === ':scope > .org-branch-card > .org-node' ? b : null;
const row = {querySelectorAll: () => [a,b]};
const svg = {style:{},setAttribute(){},set innerHTML(v){paths=[];},appendChild(p){paths.push(p);}};
const stage = {offsetWidth:1000, offsetHeight:800,scrollWidth:1000,scrollHeight:800,getBoundingClientRect:()=>box(0,0,1000,800), querySelectorAll:()=>[root,office,a,b,expert,child],querySelector: (q)=>({'.org-ceo':root,'.org-office-node':office})[q]||null};
const ctx = {$: q=>q === '.org-chart-stage' ? stage : svg, $$: q=>q === '.org-deputy-row, .org-root-department-row' ? [row] : [branch1,branch2], expandCanvasForNegativeCards(){},getComputedStyle(){return {getPropertyValue(){return '#123';}}}, document:{createElementNS(){return {style:{},setAttribute(k,v){this[k]=v;}}}}};
vm.runInNewContext(code + '\ndrawOrgWires();',ctx);
const lines = paths.map(p=>p.d);
assert(lines.includes('M 80 231 V 250'), `first card detached: ${lines}`);
assert(lines.includes('M 280 231 V 380'), `moved card detached: ${lines}`);
assert(lines.some(d=>d.startsWith('M 140 50') && d.endsWith('H 200')), `office detached: ${lines}`);
assert(lines.includes('M 80 300 V 330 H 150 V 360'), `experts detached: ${lines}`);
assert(lines.includes('M 250 482 V 500'), `subunit detached: ${lines}`);
console.log('Organization wire geometry: translated cards attach to their own edges');
